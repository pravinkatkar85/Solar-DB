function commentFor(table, col) {
  if (AUDIT[col]) return AUDIT[col];
  const key = `${table}.${col}`;
  if (COL[key]) return COL[key];
  if (col.endsWith('_id') && col === `${table.replace(/_details$/, '').replace(/^ref_/, '').replace(/^log_/, '')}_id`.replace(/s$/, '_id')) {
    return 'Surrogate primary key (GENERATED ALWAYS AS IDENTITY).';
  }
  if (FALLBACK[col]) return FALLBACK[col];
  if (col.endsWith('_ref_data_id')) return `FK to ref_data for this coded list (${col.replace(/_ref_data_id$/, '')}).`;
  if (col.endsWith('_id')) return `Foreign key ${col}.`;
  return `Column ${col}.`;
}

function pkComment(table, col) {
  if (COL[`${table}.${col}`]) return COL[`${table}.${col}`];
  return 'Surrogate primary key (GENERATED ALWAYS AS IDENTITY).';
}

function parseColumns(body) {
  const cols = [];
  const typeRe =
    /^(BIGINT|VARCHAR|CHAR|BOOLEAN|INTEGER|NUMERIC|TIMESTAMPTZ|DATE|TEXT|JSONB)\b/i;
  for (const raw of body.split('\n')) {
    const line = raw.trim().replace(/,$/, '');
    if (!line || line.startsWith('CONSTRAINT') || line.startsWith('--')) continue;
    const m = line.match(/^([a-z][a-z0-9_]*)\s+(.+)$/i);
    if (!m) continue;
    if (!typeRe.test(m[2])) continue;
    cols.push(m[1]);
  }
  return cols;
}

function emitComments(table, cols) {
  const lines = [];
  const tableCmt = TABLE[table] || `Table solar_app.${table}.`;
  lines.push(`COMMENT ON TABLE solar_app.${table} IS ${sqlStr(tableCmt)};`);
  for (const col of cols) {
    const isPk = cols.indexOf(col) === 0 && col.endsWith('_id');
    const text = isPk && !COL[`${table}.${col}`] && !AUDIT[col] ? pkComment(table, col) : commentFor(table, col);
    if (text.startsWith('Column ') && !COL[`${table}.${col}`]) {
      throw new Error(`Missing comment for ${table}.${col}`);
    }
    lines.push(`COMMENT ON COLUMN solar_app.${table}.${col} IS ${sqlStr(text)};`);
  }
  return lines.join('\n');
}

function sqlStr(s) {
  return `'${s.replace(/'/g, "''")}'`;
}

